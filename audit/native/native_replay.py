#!/usr/bin/env python3
"""Native cross-replay of the families msf.wasm cannot run (augmented pairs, character
conversions), in both directions, each with its self-control:

  cft corpus  -> cft native (control: must match cft's own record) and -> muse native (the test)
  muse corpus -> muse native (control: must match muse's own record) and -> cft native (the test)

Decimal/hex outputs are compared by exact value (the spellings legitimately differ);
inputs only one side accepts by its documented syntax are classed, not failed.
"""
import json, os, re, subprocess, sys, collections
from fractions import Fraction

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
WORK = os.environ.get('AUDIT_WORK', os.path.join(ROOT, 'dist', 'audit'))
CFTV = os.path.join(WORK, 'cft', 'vectors', 'out')          # regenerated by setup.sh, checked against SHA256SUMS
MUSEV = os.path.join(WORK, 'muse', 'tests', 'vectors')      # exported by setup.sh at MUSE_REV
XN = os.path.join(WORK, 'native', 'bin', 'xnative')
RM_CFT = {'rne': 'RNE', 'rtz': 'RTZ', 'rup': 'RUP', 'rdn': 'RDN', 'rmm': 'RMM'}
RM_MUSE = {'te': 'RNE', 'tz': 'RTZ', 'tp': 'RUP', 'tn': 'RDN', 'ta': 'RMM'}

def dec_value(s):
    s = s.strip()
    t = s.lower()
    if t in ('inf', '+inf', 'infinity', '+infinity'): return 'inf'
    if t in ('-inf', '-infinity'): return '-inf'
    if 'nan' in t: return 'nan'
    m = re.fullmatch(r'([+-]?)(\d*)(?:\.(\d*))?(?:e([+-]?\d+))?', t)
    if not m: return ('bad', s)
    sg, ip, fp, ex = m.group(1), m.group(2) or '', m.group(3) or '', int(m.group(4) or 0)
    v = Fraction(int((ip + fp) or '0')) * Fraction(10) ** (ex - len(fp))
    if v == 0: return '-0' if sg == '-' else '0'
    return -v if sg == '-' else v

def sig_digits(s):
    m = re.fullmatch(r'[+-]?(\d*)(?:\.(\d*))?(?:e[+-]?\d+)?', s.strip().lower())
    if not m: return None
    d = ((m.group(1) or '') + (m.group(2) or '')).lstrip('0')
    return len(d)

def hex_value(s):
    t = s.strip().lower()
    if 'inf' in t: return '-inf' if t.startswith('-') else 'inf'
    if 'nan' in t: return 'nan'
    m = re.fullmatch(r'([+-]?)0x([0-9a-f]*)(?:\.([0-9a-f]*))?p([+-]?\d+)', t)
    if not m: return ('bad', s)
    sg, ip, fp, ex = m.group(1), m.group(2) or '', m.group(3) or '', int(m.group(4))
    v = Fraction(int((ip + fp) or '0', 16)) * Fraction(2) ** (ex - 4 * len(fp))
    if v == 0: return '-0' if sg == '-' else '0'
    return -v if sg == '-' else v

def isnan(bits, F):
    e = (bits >> (23 if F == 32 else 52)) & (0xff if F == 32 else 0x7ff)
    return e == (0xff if F == 32 else 0x7ff) and bits & ((1 << (23 if F == 32 else 52)) - 1)

def build_requests():
    """Every request, both corpora: (request line, meta)."""
    reqs = []          # (request line, meta)
    # ---------------- cft corpus
    for F in (32, 64):
        for l in open(os.path.join(CFTV, f'fp{F}-augmented.jsonl')):
            r = json.loads(l)
            fn = {'augmentedAddition': 'add', 'augmentedSubtraction': 'sub', 'augmentedMultiplication': 'mul'}[r['fn']]
            reqs.append((f"AUG {F} {fn} {int(r['a'], 16):x} {int(r['b'], 16):x}",
                         dict(src='cft', fam='augmented', F=F, exp=(int(r['r'], 16), int(r['e'], 16), r['flags']))))
        for suf in ('', '-rtz', '-rup', '-rdn', '-rmm'):
            for l in open(os.path.join(CFTV, f'fp{F}-character{suf}.jsonl')):
                r = json.loads(l)
                rm = RM_CFT[r.get('rnd', 'rne')]
                fn = r['fn']
                if fn in ('from_decimal', 'from_hex'):
                    s = r['s']
                    if not s or any(c.isspace() for c in s):
                        continue
                    exp = None if r.get('refuse') else (int(r['d'], 16), r['flags'])
                    reqs.append((f"{'FROMDEC' if fn == 'from_decimal' else 'FROMHEX'} {F} {rm} {s}",
                                 dict(src='cft', fam=fn, F=F, exp=exp, s=s)))
                elif fn == 'to_decimal':
                    dg = r['digits']
                    if dg == 0:
                        n = sig_digits(r['s'])
                        if not n: continue            # zero/special: digit count undefined; covered by digits>=1 rows
                        dg_req, exact = n, True
                    else:
                        dg_req, exact = dg, False
                    reqs.append((f"TODEC {F} {rm} {int(r['a'], 16):x} {dg_req}",
                                 dict(src='cft', fam='to_decimal', F=F, exp=(r['s'], r['flags']), exact=exact, digits=dg)))
                elif fn == 'to_hex':
                    reqs.append((f"TOHEX {F} {int(r['a'], 16):x}", dict(src='cft', fam='to_hex', F=F, exp=(r['s'], 0))))
    # ---------------- muse corpus
    def muse_lines(fn):
        for l in open(os.path.join(MUSEV, fn)):
            if l.startswith('#') or not l.strip(): continue
            yield l.split()
    for F in (32, 64):
        for t in muse_lines(f'aug-f{F}.vec'):
            op, _, a, b, _arrow, h, tl, fl = t[:8]
            fn = op.rsplit('_', 1)[1]
            reqs.append((f"AUG {F} {fn} {a} {b}", dict(src='muse', fam='augmented', F=F, exp=(int(h, 16), int(tl, 16), int(fl, 16)))))
    for t in muse_lines('from-decimal-str.vec'):
        op, rm, inp, _arrow, bits, fl, C = t[:7]
        F = int(op[3:5]) if op[3:5] in ('32', '64') else 16
        if F == 16: continue
        s = inp[3:]
        reqs.append((f"FROMDEC {F} {RM_MUSE[rm]} {s if s else '~'}",
                     dict(src='muse', fam='from_decimal', F=F, exp=(int(bits, 16), int(fl, 16)), C=int(C[2:]), s=s)))
    for t in muse_lines('from-hex-str.vec'):
        op, rm, inp, _arrow, bits, fl, C = t[:7]
        F = int(op[3:5]) if op[3:5] in ('32', '64') else 16
        if F == 16: continue
        s = inp[3:]
        reqs.append((f"FROMHEX {F} {RM_MUSE[rm]} {s if s else '~'}",
                     dict(src='muse', fam='from_hex', F=F, exp=(int(bits, 16), int(fl, 16)), C=int(C[2:]), s=s)))
    for t in muse_lines('to-decimal-str.vec'):
        if any(x.startswith('BUF=') for x in t): continue        # muse's buffer-size semantics: no cft counterpart
        op, rm, A, SPEC, _arrow, OUT, LEN, fl = t[:8]
        F = int(op[3:5]) if op[3:5] in ('32', '64') else 16
        if F == 16: continue
        prec, style, mind = (int(x) for x in SPEC[5:].split(','))
        if style != 0 or mind != 0:
            continue                                  # fixed style / padded: cft has scientific only
        dg = prec if prec > 0 else (9 if F == 32 else 17)
        reqs.append((f"TODEC {F} {RM_MUSE[rm]} {A[2:]} {dg}", dict(src='muse', fam='to_decimal', F=F, exp=(OUT[4:], int(fl, 16)), spec=SPEC)))
    for t in muse_lines('to-hex-str.vec'):
        if any(x.startswith('BUF=') for x in t): continue
        op, rm, A, SPEC, _arrow, OUT, LEN, fl = t[:8]
        F = int(op[3:5]) if op[3:5] in ('32', '64') else 16
        if F == 16 or SPEC != 'SPEC=-1': continue
        reqs.append((f"TOHEX {F} {A[2:]}", dict(src='muse', fam='to_hex', F=F, exp=(OUT[4:], int(fl, 16)))))
    return reqs

def run(reqs):
    """xnative's answer line for each request, in order."""
    out = subprocess.run([XN], input='\n'.join(q for q, _ in reqs) + '\n', capture_output=True, text=True, check=True).stdout.splitlines()
    assert len(out) == len(reqs), (len(out), len(reqs))
    return out

def main():
    reqs = build_requests()
    print('requests', len(reqs), collections.Counter((m['src'], m['fam']) for _, m in reqs))

    out = run(reqs)

    tally = collections.Counter(); ex = collections.defaultdict(list)
    def note(key, line):
        tally[key] += 1
        if len(ex[key]) < 3: ex[key].append(line)

    for (q, m), line in zip(reqs, out):
        _, mpart, cpart = line.split(' | ')
        mt, ct = mpart.split()[1:], cpart.split()[1:]
        F, fam, src = m['F'], m['fam'], m['src']
        sides = {'muse': mt, 'cft': ct}
        # who is under test, who is the control: the corpus's own library is the control
        test, ctrl = ('muse', 'cft') if src == 'cft' else ('cft', 'muse')
        for who in (ctrl, test):
            role = 'control' if who == ctrl else 'CROSS'
            t = sides[who]
            tag = f'{src}-corpus -> {who} [{role}] {fam}@{F}'
            if fam == 'augmented':
                if who == 'cft':
                    st, h, tl, fl = int(t[0]), int(t[1], 16), int(t[2], 16), int(t[3], 16)
                    if st: note((tag, 'refused'), line); continue
                else:
                    h, tl, fl = int(t[0], 16), int(t[1], 16), int(t[2], 16)
                eh, et, ef = m['exp']
                vals = (h == eh or (isnan(h, F) and isnan(eh, F))) and (tl == et or (isnan(tl, F) and isnan(et, F)))
                nanb = vals and (h != eh or tl != et)
                note((tag, 'ok' if vals and fl == ef and not nanb else 'nan-bits' if vals and fl == ef else
                      f'flags {ef:02x}->{fl:02x}' if vals else 'VALUE'), line)
            elif fam in ('from_decimal', 'from_hex'):
                if who == 'cft':
                    st, bits, fl = int(t[0]), int(t[1], 16), int(t[2], 16)
                    if st:
                        note((tag, 'refused (cft syntax: whole string only)'), line); continue
                else:
                    bits, fl = int(t[0], 16), int(t[1], 16)
                    C, L = int(t[2][2:]), int(t[3][4:])
                    if src == 'cft' and C != L:
                        note((tag, 'prefix-only (muse syntax: longest valid prefix)'), line); continue
                if m['exp'] is None:
                    note((tag, 'accepted where cft refuses'), line); continue
                if src == 'muse' and who == 'cft' and m['C'] != len(m['s']):
                    note((tag, 'muse expects a prefix parse'), line); continue
                eb, ef = m['exp']
                ok = (bits == eb or (isnan(bits, F) and isnan(eb, F)))
                key = 'ok' if ok and fl == ef else (f'flags {ef:02x}->{fl:02x}' if ok else 'VALUE')
                if key != 'ok' and fam == 'from_decimal':
                    n = sig_digits(m['s'])
                    if n is not None and n > 20:
                        key += ' (>20 significant digits: muse H=20 two-step route)'
                note((tag, key), line)
            elif fam == 'to_decimal':
                if who == 'cft':
                    st, s_out, fl = int(t[0]), t[1], int(t[2], 16)
                    if st: note((tag, 'refused'), line); continue
                else:
                    s_out, fl = t[0], int(t[1], 16)
                es, ef = m['exp']
                v, ev = dec_value(s_out), dec_value(es)
                if m.get('exact'):
                    ef = 0x10 if v != ev else 0     # cft's digits=0 is exact and flagless; asked with as many digits, inexact iff dropped
                same_digits = sig_digits(s_out) == sig_digits(es) or v in ('0', '-0', 'inf', '-inf', 'nan')
                key = 'ok' if v == ev and fl == ef and same_digits else ('VALUE' if v != ev else f'flags {ef:02x}->{fl:02x}' if fl != ef else 'digit count')
                note((tag, key), line)
            elif fam == 'to_hex':
                if who == 'cft':
                    st, s_out = int(t[0]), t[1]
                    if st: note((tag, 'refused'), line); continue
                else:
                    s_out = t[0]
                es = m['exp'][0]
                v, ev = hex_value(s_out), hex_value(es)
                note((tag, 'ok' if v == ev else 'VALUE'), line)

    print()
    for (tag, key), n in sorted(tally.items()):
        print(f'{n:8d}  {tag:<52} {key}')
    print()
    for (tag, key), lines in sorted(ex.items()):
        if key != 'ok':
            for l in lines: print(f'[{tag} :: {key}] {l[:260]}')

if __name__ == '__main__':
    main()
